/**
 * Applies a selected 64-color palette to the active JSNES PPU instance.
 * Encodes colors in Little-Endian Canvas format ((B << 16) | (G << 8) | R) so that
 * when the PPU writes to its framebuffer, byte 0 is Red, byte 1 is Green, byte 2 is Blue.
 */
export function applyPaletteToNes(nesInstance: any, paletteId: ColorPaletteId) {
  if (!nesInstance || !nesInstance.ppu || !nesInstance.ppu.palTable) return;
  const palTable = nesInstance.ppu.palTable;
  const def = PALETTES[paletteId] || PALETTES["fbx-smooth"];
  const colors = def.colors;

  const cur = new Uint32Array(64);
  for (let i = 0; i < 64; i++) {
    const r = colors[i * 3];
    const g = colors[i * 3 + 1];
    const b = colors[i * 3 + 2];
    cur[i] = ((b & 0xff) << 16) | ((g & 0xff) << 8) | (r & 0xff);
  }
  palTable.curTable = cur;

  // Build all 8 emphasis lookup tables
  for (let emph = 0; emph < 8; emph++) {
    let rFactor = 1.0;
    let gFactor = 1.0;
    let bFactor = 1.0;
    if ((emph & 1) !== 0) {
      gFactor = 0.75;
      bFactor = 0.75;
    }
    if ((emph & 2) !== 0) {
      rFactor = 0.75;
      bFactor = 0.75;
    }
    if ((emph & 4) !== 0) {
      rFactor = 0.75;
      gFactor = 0.75;
    }

    const table = new Uint32Array(64);
    for (let i = 0; i < 64; i++) {
      const r = Math.floor(colors[i * 3] * rFactor);
      const g = Math.floor(colors[i * 3 + 1] * gFactor);
      const b = Math.floor(colors[i * 3 + 2] * bFactor);
      table[i] = ((b & 0xff) << 16) | ((g & 0xff) << 8) | (r & 0xff);
    }
    palTable.emphTable[emph] = table;
  }

  palTable.currentEmph = 0;
  for (let i = 0; i < 64; i++) {
    palTable.curTable[i] = palTable.emphTable[0][i];
  }

  // Instruct PPU to immediately synchronize imgPalette and sprPalette
  if (typeof nesInstance.ppu.updatePalettes === "function") {
    nesInstance.ppu.updatePalettes();
  }
}
