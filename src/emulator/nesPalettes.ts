// Helper to generate 64-color Game Boy DMG palette mapped to NES brightness steps
function createGameBoyDmgPalette(): number[] {
  const shades: [number, number, number][] = [
    [0x0f, 0x38, 0x0f], // Darkest green
    [0x30, 0x62, 0x30], // Dark green
    [0x8b, 0xac, 0x0f], // Light green
    [0x9b, 0xbc, 0x0f], // Lightest green
  ];
  const out: number[] = [];
  for (let i = 0; i < 64; i++) {
    const row = Math.floor(i / 16);
    const shadeIdx = Math.min(3, Math.max(0, row));
    const [r, g, b] = shades[shadeIdx];
    out.push(r, g, b);
  }
  return out;
}

// Helper to generate 64-color Monochrome grayscale palette
function createMonochromePalette(): number[] {
  const out: number[] = [];
  for (let i = 0; i < 64; i++) {
    // Map based on FBX luminance
    const r = FBX_SMOOTH_RGB[i * 3];
    const g = FBX_SMOOTH_RGB[i * 3 + 1];
    const b = FBX_SMOOTH_RGB[i * 3 + 2];
    const lum = Math.round(0.299 * r + 0.587 * g + 0.114 * b);
    out.push(lum, lum, lum);
  }
  return out;
}

