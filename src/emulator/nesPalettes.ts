/**
 * Converts standard CSS/hex 0xRRGGBB (e.g. 0x38bdf8) to Little-Endian 32-bit Canvas pixel 0xAABBGGRR.
 * In little-endian memory (Canvas ImageData.data):
 * Byte 0 (bits 0..7)   = Red
 * Byte 1 (bits 8..15)  = Green
 * Byte 2 (bits 16..23) = Blue
 * Byte 3 (bits 24..31) = Alpha
 */
export function hexRgb(hex: number, a: number = 255): number {
  const r = (hex >> 16) & 0xff;
  const g = (hex >> 8) & 0xff;
  const b = hex & 0xff;
  return ((a & 0xff) << 24) | (b << 16) | (g << 8) | r;
}

export function rgbLe(r: number, g: number, b: number, a: number = 255): number {
  return ((a & 0xff) << 24) | ((b & 0xff) << 16) | ((g & 0xff) << 8) | (r & 0xff);
}

